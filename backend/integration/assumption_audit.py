"""Bounded experiments using the existing B11 engine; no alternative model.

JSON stdin/stdout, compact summaries only. The housing cohort is pinned across
incoming-load, service, and no-new-homes treatments for each seed. Incoming
riders remain generated by B11, using its vehicle-keyed random streams.
"""
import copy
import hashlib
import json
import sys
from dataclasses import replace

from backend.simulation import runner
from backend.simulation.paired_runs import run_repeated_simulations
from data.simulation_input import load_simulation_input


def execute(request):
    baseline = load_simulation_input()
    seeds = request['seeds']
    if not 3 <= len(seeds) <= 20 or len(set(seeds)) != len(seeds):
        raise ValueError('Supply 3 to 20 distinct seeds')
    original = runner.generate_passengers
    cohorts = {}
    signatures = {}

    def cohort(inputs):
        # Demand deliberately changes the population; operations never do.
        key = (inputs.seed, inputs.trips_per_resident_in_window)
        if key not in cohorts:
            full = replace(inputs, developments=baseline.developments)
            cohorts[key] = original(full)
        passengers = cohorts[key]
        if not inputs.developments:
            passengers = {k: p for k, p in passengers.items() if p.rider_group == 'existing'}
        existing = sorted((p.id, p.origin_stop_id, p.destination_stop_id,
                           round(p.get_to_stop_time, 6))
                          for p in passengers.values() if p.rider_group == 'existing')
        signatures[inputs.seed] = hashlib.sha256(json.dumps(existing).encode()).hexdigest()
        return copy.deepcopy(passengers)

    outputs = []
    try:
        runner.generate_passengers = cohort
        for recipe in request['recipes']:
            overrides = dict(incoming_load_range=recipe['incoming_load_range'],
                             trips_per_resident_in_window=baseline.trips_per_resident_in_window * recipe['demand_factor'],
                             headway_s=recipe['headway_s'])
            if recipe['headway_s'] != baseline.headway_s:
                overrides['entry_schedule_s'] = ()
            if not recipe.get('new_homes', True):
                overrides['developments'] = []
            inputs = load_simulation_input(overrides=overrides)

            def compact(result):
                if not result['summary']['overview']['conservation_valid']:
                    raise ValueError('B11 conservation check failed')
                return dict(inputs={'seed': result['inputs']['seed'],
                                    'existing_cohort_signature': signatures[result['inputs']['seed']]},
                            summary=result['summary'])

            batch = run_repeated_simulations(inputs, run_count=len(seeds), seeds=seeds,
                                             result_transform=compact)
            outputs.append(dict(recipe=recipe, batch_id=batch['id'],
                                overall_results=batch['overall_results'], runs=batch['individual_results']))
    finally:
        runner.generate_passengers = original
    return outputs


if __name__ == '__main__':
    try:
        json.dump(execute(json.load(sys.stdin)), sys.stdout, allow_nan=False)
    except Exception as error:
        print(type(error).__name__, file=sys.stderr)
        sys.exit(1)
